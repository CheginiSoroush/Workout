export interface RestStretchRec {
  id: string; // شناسهٔ حرکت در STRETCH_ROUTINE (mobility.ts)
  reason: string; // چرا امروز؟ — به تمرین روز قبل وصل است
}

export interface RestDayPlan {
  id: string; // sun | tue | thu | fri
  jsDay: number; // 0 | 2 | 4 | 5 — مپینگ Date.getDay()
  weekDay: string; // نام روز
  type: "active" | "full-rest" | "prep";
  typeLabel: string; // ریکاوری فعال / استراحت کامل / آماده‌سازی هفته
  icon: LucideIcon;
  // اتصال به تمرین قبلی
  prevWorkout?: string; // «جلسهٔ ۱ — Push (سینه، سرشانه، پشت‌بازو)»
  why: string; // چرا این برنامه برای امروز — منطق اتصال به دیروز
  // فعالیت اصلی روز
  activity: string;
  activityHint: string;
  // دوچرخهٔ اختیاری (ریکاوری فعال)
  bike?: string;
  // کشش‌های پیشنهادی امروز — با دلیل اتصال به تمرین دیروز
  stretches: RestStretchRec[];
  // وظایف ویژهٔ روز (مثل آماده‌سازی هفتهٔ بعد)
  prepTasks: string[];
}

